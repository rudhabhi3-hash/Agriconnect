// ============================================================
// NORMALIZE TEXT
// ============================================================

export function normalizeText(value = '') {
  return value
    .replace(/\s+/g, ' ')
    .trim()
}


// ============================================================
// ESCAPE REGEX
// ============================================================

function escapeRegExp(value) {
  return value.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')
}


// ============================================================
// DYNAMIC WORD TRANSLATION
// ============================================================

function translateDynamicWords(text) {
  let result = text

  const entries = Object.entries(dynamicWords).sort(
    ([a], [b]) => b.length - a.length
  )

  entries.forEach(([english, hindi]) => {
    const escaped = escapeRegExp(english)

    const regex = new RegExp(
      `(^|[^A-Za-z])${escaped}(?=$|[^A-Za-z])`,
      'gi'
    )

    result = result.replace(
      regex,
      match => {
        const prefix = match.match(/^[^A-Za-z]*/)?.[0] || ''
        return prefix + hindi
      }
    )
  })

  return result
}


// ============================================================
// NUMERIC / AGRICULTURAL VALUE TRANSLATION
// ============================================================

function translateNumbers(text) {
  let result = text

  // ----------------------------------------------------------
  // Quantity
  // 20 tonnes -> 20 टन
  // 20 Tonnes -> 20 टन
  // ----------------------------------------------------------

  result = result.replace(
    /(\d+(?:\.\d+)?)\s+tonnes?/gi,
    '$1 टन'
  )

  // ----------------------------------------------------------
  // Days
  // 3 days -> 3 दिन
  // ----------------------------------------------------------

  result = result.replace(
    /(\d+(?:\.\d+)?)\s+days?/gi,
    '$1 दिन'
  )

  // ----------------------------------------------------------
  // Weeks
  // ----------------------------------------------------------

  result = result.replace(
    /(\d+(?:\.\d+)?)\s+weeks?/gi,
    '$1 सप्ताह'
  )

  // ----------------------------------------------------------
  // Months
  // ----------------------------------------------------------

  result = result.replace(
    /(\d+(?:\.\d+)?)\s+months?/gi,
    '$1 महीने'
  )

  // ----------------------------------------------------------
  // Confidence
  // 84% confidence
  // ----------------------------------------------------------

  result = result.replace(
    /(\d+(?:\.\d+)?)%\s*confidence/gi,
    '$1% विश्वास स्तर'
  )

  // ----------------------------------------------------------
  // Growth
  // +18% growth
  // ----------------------------------------------------------

  result = result.replace(
    /([+-]?\d+(?:\.\d+)?)%\s*growth/gi,
    '$1% वृद्धि'
  )

  // ----------------------------------------------------------
  // Demand growth
  // ----------------------------------------------------------

  result = result.replace(
    /([+-]?\d+(?:\.\d+)?)%\s*demand\s*growth/gi,
    '$1% मांग वृद्धि'
  )

  // ----------------------------------------------------------
  // ₹34/kg
  // ----------------------------------------------------------

  result = result.replace(
    /₹\s*([\d,.]+)\s*\/\s*kg/gi,
    '₹$1/किग्रा'
  )

  // ----------------------------------------------------------
  // ₹34 per kg
  // ----------------------------------------------------------

  result = result.replace(
    /₹\s*([\d,.]+)\s+per\s+kg/gi,
    '₹$1 प्रति किग्रा'
  )

  // ----------------------------------------------------------
  // 20T
  // ----------------------------------------------------------

  result = result.replace(
    /(\d+(?:\.\d+)?)T\b/g,
    '$1 टन'
  )

  // ----------------------------------------------------------
  // /kg
  // ----------------------------------------------------------

  result = result.replace(
    /\/kg\b/gi,
    '/किग्रा'
  )

  return result
}


// ============================================================
// DYNAMIC SENTENCE TRANSLATION
// ============================================================

function translateDynamicSentence(text) {
  let result = text

  // ----------------------------------------------------------
  // Good morning, Aditya.
  // ----------------------------------------------------------

  result = result.replace(
    /^Good morning,\s*(.+?)\.$/i,
    'सुप्रभात, $1।'
  )

  // ----------------------------------------------------------
  // Tomato · Delhi NCR
  // ----------------------------------------------------------

  result = result.replace(
    /^(.+?)\s*·\s*(.+?)$/,
    (_, first, second) => {
      return (
        translateDynamicWords(first) +
        ' · ' +
        translateDynamicWords(second)
      )
    }
  )

  // ----------------------------------------------------------
  // 20 tonnes of Tomato
  // ----------------------------------------------------------

  result = result.replace(
    /^(\d+(?:\.\d+)?)\s+tonnes?\s+of\s+(.+)$/i,
    (_, quantity, crop) => {
      return `${quantity} टन ${translateDynamicWords(crop)}`
    }
  )

  // ----------------------------------------------------------
  // 20 tonnes of Tomato to Delhi NCR
  // ----------------------------------------------------------

  result = result.replace(
    /^(\d+(?:\.\d+)?)\s+tonnes?\s+of\s+(.+?)\s+to\s+(.+?)\.?$/i,
    (_, quantity, crop, destination) => {
      return (
        `${quantity} टन ` +
        `${translateDynamicWords(crop)} ` +
        `को ${translateDynamicWords(destination)}`
      )
    }
  )

  // ----------------------------------------------------------
  // Forecast unavailable for Tomato.
  // ----------------------------------------------------------

  result = result.replace(
    /^Forecast unavailable for\s+(.+?)\.?$/i,
    (_, crop) => {
      return `${translateDynamicWords(crop)} के लिए पूर्वानुमान उपलब्ध नहीं है।`
    }
  )

  // ----------------------------------------------------------
  // Expected demand in the next 7 days
  // ----------------------------------------------------------

  result = result.replace(
    /^Expected demand in the next 7 days\.?$/i,
    'अगले 7 दिनों में अपेक्षित मांग'
  )

  // ----------------------------------------------------------
  // X% growth
  // ----------------------------------------------------------

  result = result.replace(
    /^([+-]?\d+(?:\.\d+)?)%\s*growth$/i,
    (_, value) => `${value}% वृद्धि`
  )

  // ----------------------------------------------------------
  // X% confidence
  // ----------------------------------------------------------

  result = result.replace(
    /^(\d+(?:\.\d+)?)%\s*confidence$/i,
    (_, value) => `${value}% विश्वास स्तर`
  )

  // ----------------------------------------------------------
  // Production ₹18/kg
  // ----------------------------------------------------------

  result = result.replace(
    /^Production\s*(₹?.+)$/i,
    (_, value) => `उत्पादन ${value}`
  )

  // ----------------------------------------------------------
  // Fertilizer ₹2/kg
  // ----------------------------------------------------------

  result = result.replace(
    /^Fertilizer\s*(₹?.+)$/i,
    (_, value) => `उर्वरक ${value}`
  )

  // ----------------------------------------------------------
  // Labour ₹3/kg
  // ----------------------------------------------------------

  result = result.replace(
    /^Labou?r\s*(₹?.+)$/i,
    (_, value) => `श्रम ${value}`
  )

  // ----------------------------------------------------------
  // Transport ₹4.5/kg
  // ----------------------------------------------------------

  result = result.replace(
    /^Transport\s*(₹?.+)$/i,
    (_, value) => `परिवहन ${value}`
  )

  // ----------------------------------------------------------
  // Handling / Storage ₹1/kg
  // ----------------------------------------------------------

  result = result.replace(
    /^Handling\s*\/?\s*Storage\s*(₹?.+)$/i,
    (_, value) => `हैंडलिंग / भंडारण ${value}`
  )

  // ----------------------------------------------------------
  // Other ₹0.5/kg
  // ----------------------------------------------------------

  result = result.replace(
    /^Other\s*(₹?.+)$/i,
    (_, value) => `अन्य ${value}`
  )

  return result
}


// ============================================================
// MAIN TRANSLATION FUNCTION
// ============================================================

export function translateText(value, language = 'en') {
  if (!value || language === 'en') {
    return value
  }

  const originalValue = value
  const normalized = normalizeText(value)

  if (!normalized) {
    return value
  }

  // ----------------------------------------------------------
  // 1. Exact translation
  // ----------------------------------------------------------

  if (enHi[normalized]) {
    const leading =
      originalValue.match(/^\s*/)?.[0] || ''

    const trailing =
      originalValue.match(/\s*$/)?.[0] || ''

    return (
      leading +
      enHi[normalized] +
      trailing
    )
  }

  // ----------------------------------------------------------
  // 2. Dynamic sentence patterns
  // ----------------------------------------------------------

  let translated = translateDynamicSentence(normalized)

  // ----------------------------------------------------------
  // 3. Dynamic numeric values
  // ----------------------------------------------------------

  translated = translateNumbers(translated)

  // ----------------------------------------------------------
  // 4. Dynamic agricultural words
  // ----------------------------------------------------------

  translated = translateDynamicWords(translated)

  // ----------------------------------------------------------
  // 5. Preserve original whitespace
  // ----------------------------------------------------------

  const leading =
    originalValue.match(/^\s*/)?.[0] || ''

  const trailing =
    originalValue.match(/\s*$/)?.[0] || ''

  return (
    leading +
    translated +
    trailing
  )
}


